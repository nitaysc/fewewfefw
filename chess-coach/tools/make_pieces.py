"""Builds www/css/pieces-<set>.css (one file per piece set, SVGs inlined) and piece-previews.css.

The sets come from the lichess-org/lila repository; only sets with a free licence are used:
  cburnett   Colin M.L. Burnett        GPLv2+
  merida     Armando Hernandez Marroquin  GPLv2+
  celtic     Maurizio Monge            MIT
  chessnut   Alexis Luengas            Apache 2.0
  kiwen-suwi neverRare                 CC BY 4.0
Files are fetched once into tools/.cache and checked against tools/pieces.lock (SHA-256).

Run: python3 tools/make_pieces.py
"""
import base64, hashlib, json, os, sys, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, '.cache', 'pieces')
LOCK = os.path.join(HERE, 'pieces.lock')
CSS = os.path.join(HERE, '..', 'www', 'css')
BASE = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/%s/%s.svg'
SETS = [
    ('cburnett', 'Colin M.L. Burnett, GPLv2+'),
    ('merida', 'Armando Hernandez Marroquin, GPLv2+'),
    ('celtic', 'Maurizio Monge, MIT'),
    ('chessnut', 'Alexis Luengas, Apache 2.0'),
    ('kiwen-suwi', 'neverRare, CC BY 4.0'),
]
PIECES = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP']


def main():
    lock = json.load(open(LOCK)) if os.path.exists(LOCK) else {}
    new_lock = {}
    previews = '/* One knight from each piece set, for the picker. Generated by tools/make_pieces.py. */\n'
    for name, credit in SETS:
        os.makedirs(os.path.join(CACHE, name), exist_ok=True)
        css = '/* Piece set "%s" by %s (from lichess-org/lila). Generated by tools/make_pieces.py. */\n' % (name, credit)
        for pc in PIECES:
            path = os.path.join(CACHE, name, pc + '.svg')
            if not os.path.exists(path):
                with urllib.request.urlopen(BASE % (name, pc), timeout=60) as r, open(path, 'wb') as f:
                    f.write(r.read())
            data = open(path, 'rb').read()
            key = name + '/' + pc
            sha = hashlib.sha256(data).hexdigest()
            if key in lock and lock[key] != sha:
                sys.exit('checksum mismatch for ' + key)
            new_lock[key] = sha
            uri = 'data:image/svg+xml;base64,' + base64.b64encode(data).decode()
            css += '.pc.%s%s{background-image:url("%s")}\n' % (pc[0], pc[1].lower(), uri)
            if pc == 'wN':
                previews += '.pv-%s{background-image:url("%s")}\n' % (name, uri)
        with open(os.path.join(CSS, 'pieces-%s.css' % name), 'w') as f:
            f.write(css)
        print('%-11s %5.1f KB' % (name, len(css) / 1024))
    with open(os.path.join(CSS, 'piece-previews.css'), 'w') as f:
        f.write(previews)
    json.dump(new_lock, open(LOCK, 'w'), indent=1, sort_keys=True)


if __name__ == '__main__':
    main()
